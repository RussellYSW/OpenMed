"""Serialization of benchmark results: JSON for machines, Markdown for people.

Both renderings carry the same provenance line, because a benchmark number
without the command that produced it is not evidence. The tolerance column
names which guarantee a row is being judged against, because "within tolerance"
means different things for a threshold rule and for a bounded-influence one. Nothing here rounds, hides
or reorders results to make a defense look better: rows are emitted in the order
they were run, and every row states the seed it came from.
"""

from __future__ import annotations

import json
import platform
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np

from trustfed.aggregation.tolerance import tolerance_table
from trustfed.benchmark.errors import BenchmarkError
from trustfed.benchmark.runner import ScenarioResult

PROVENANCE = (
    "Generated by `python -m trustfed.benchmark`. All data is synthetic "
    "(trustfed.data); no patient data is involved. Numbers describe this "
    "simulation only and are not clinical performance claims."
)


@dataclass
class BenchmarkReport:
    """A collection of :class:`~trustfed.benchmark.runner.ScenarioResult` rows."""

    results: List[ScenarioResult] = field(default_factory=list)

    def __len__(self) -> int:
        return len(self.results)

    def __iter__(self):
        return iter(self.results)

    @property
    def seeds(self) -> List[int]:
        """Sorted list of the seeds represented in this report."""
        return sorted({r.scenario.seed for r in self.results})

    def clean_baselines(self) -> Dict[str, float]:
        """Map ``aggregator@seed`` -> final AUC of its no-attack run, if present."""
        out: Dict[str, float] = {}
        for r in self.results:
            if r.scenario.attack == "none":
                out[f"{r.scenario.aggregator}@{r.scenario.seed}"] = r.final_auc
        return out

    def delta_vs_clean(self, result: ScenarioResult) -> Optional[float]:
        """AUC change relative to the same aggregator's clean run, if available."""
        key = f"{result.scenario.aggregator}@{result.scenario.seed}"
        base = self.clean_baselines().get(key)
        if base is None:
            return None
        return result.final_auc - base

    def worst_case(self) -> Dict[str, float]:
        """Per aggregator, the lowest final AUC across all attacked scenarios.

        This is the number that matters for a defense: not how well it does on
        average, but how badly it can be made to do.
        """
        out: Dict[str, float] = {}
        for r in self.results:
            if r.scenario.attack == "none":
                continue
            key = r.scenario.aggregator
            out[key] = min(out.get(key, float("inf")), r.final_auc)
        return out

    def to_dict(self, *, include_timing: bool = False) -> Dict[str, Any]:
        """JSON-serializable view of the whole report."""
        return {
            "provenance": PROVENANCE,
            "seeds": self.seeds,
            "n_results": len(self.results),
            "environment": {
                "python": platform.python_version(),
                "numpy": np.__version__,
            },
            "worst_case_auc_by_aggregator": {
                k: round(v, 6) for k, v in sorted(self.worst_case().items())
            },
            "results": [
                r.to_dict(include_timing=include_timing) for r in self.results
            ],
        }

    def to_json(self, *, include_timing: bool = False) -> str:
        """Render as UTF-8 JSON with sorted keys and a trailing newline."""
        return (
            json.dumps(
                self.to_dict(include_timing=include_timing),
                indent=2,
                sort_keys=True,
                ensure_ascii=False,
            )
            + "\n"
        )

    def to_markdown(self, *, title: str = "TrustFed defense benchmark") -> str:
        """Render as a Markdown document with one table row per scenario."""
        lines: List[str] = [f"# {title}", "", PROVENANCE, ""]
        lines.append(
            f"Seeds: {', '.join(str(s) for s in self.seeds)} | "
            f"scenarios: {len(self.results)} | "
            f"python {platform.python_version()}, numpy {np.__version__}"
        )
        lines += [
            "",
            "| aggregator | attack | n | f | f/n | final AUC | vs clean | "
            "rejected | guarantee tested | f <= exact-recovery bound |",
            "|---|---|---:|---:|---:|---:|---:|---:|---|:--:|",
        ]
        for r in self.results:
            s = r.scenario
            delta = self.delta_vs_clean(r)
            delta_txt = "--" if delta is None else f"{delta:+.3f}"
            ok = "yes" if r.within_tolerance else "NO"
            guarantee = r.guarantee_kind
            if r.influence_bound is not None:
                guarantee += f" (bias <= {r.influence_bound:.2f}*tau)"
            lines.append(
                f"| `{s.aggregator}` | {s.attack} | {s.n_sites} | {s.n_byzantine} | "
                f"{s.byzantine_fraction:.2f} | {r.final_auc:.3f} | {delta_txt} | "
                f"{r.n_rejected_total} | {guarantee} | {ok} |"
            )

        worst = self.worst_case()
        if worst:
            lines += ["", "## Worst case per aggregator", ""]
            lines += ["| aggregator | lowest final AUC under any attack |", "|---|---:|"]
            for key in sorted(worst, key=lambda k: -worst[k]):
                lines.append(f"| `{key}` | {worst[key]:.3f} |")

        lines += [
            "",
            "## Documented Byzantine tolerance",
            "",
            "Analytical bounds from the source papers, not measurements:",
            "",
            tolerance_table().rstrip("\n"),
            "",
            "A `NO` in the last column means the scenario's f is outside the",
            "range where the rule is claimed to recover the honest signal",
            "*exactly*, so a poor result there is expected behaviour rather than",
            "a defect. It is `NO` for every attacked bounded-influence row by",
            "construction: `norm_clip` never removes an attacker's contribution,",
            "it only caps it, so its guarantee is the `2*tau*f/n` displacement",
            "bound in the `guarantee tested` column and not exact recovery.",
            "",
        ]
        return "\n".join(lines) + "\n"

    def write(
        self,
        directory: Path,
        *,
        stem: str = "benchmark",
        include_timing: bool = False,
    ) -> Dict[str, Path]:
        """Write ``<stem>.json`` and ``<stem>.md`` into ``directory``.

        Returns the paths written, keyed ``"json"`` and ``"markdown"``.

        Raises
        ------
        BenchmarkError
            If the report is empty (writing an empty benchmark is more likely a
            bug than an intention).
        """
        if not self.results:
            raise BenchmarkError("refusing to write an empty benchmark report")
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        json_path = directory / f"{stem}.json"
        md_path = directory / f"{stem}.md"
        json_path.write_text(
            self.to_json(include_timing=include_timing), encoding="utf-8"
        )
        md_path.write_text(self.to_markdown(), encoding="utf-8")
        return {"json": json_path, "markdown": md_path}


def load_report(path: Path) -> Dict[str, Any]:
    """Load a previously written benchmark JSON file as a plain dict."""
    return json.loads(Path(path).read_text(encoding="utf-8"))


def compare_reports(
    baseline: Dict[str, Any], candidate: Dict[str, Any], *, tolerance: float = 1e-9
) -> List[str]:
    """List scenarios whose final AUC differs between two report dicts.

    Used to check reproducibility: two runs of the same grid at the same seed
    should return an empty list.
    """
    def index(report: Dict[str, Any]) -> Dict[str, float]:
        """Map scenario name -> final AUC."""
        return {
            row["scenario"]["name"]: row["final_auc"]
            for row in report.get("results", [])
        }

    a, b = index(baseline), index(candidate)
    diffs: List[str] = []
    for key in sorted(set(a) | set(b)):
        if key not in a or key not in b:
            diffs.append(f"{key}: present in only one report")
        elif abs(a[key] - b[key]) > tolerance:
            diffs.append(f"{key}: {a[key]:.6f} != {b[key]:.6f}")
    return diffs


__all__ = ["BenchmarkReport", "PROVENANCE", "load_report", "compare_reports"]
